CREATE TABLE IF NOT EXISTS ai_core.managers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_code  text NOT NULL UNIQUE,
    name          text NOT NULL,
    domain        text,
    status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','deprecated')),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ai_core.agents (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_code       text NOT NULL UNIQUE,
    name             text NOT NULL,
    role             text,
    manager_id       bigint REFERENCES ai_core.managers(id),
    model            text,
    version          text,
    status           text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','disabled','deprecated')),
    memory_scope     text,
    max_concurrency  integer NOT NULL DEFAULT 1,
    current_load     integer NOT NULL DEFAULT 0,
    quality_score    numeric(4,3),
    success_rate     numeric(4,3),
    speed_score      numeric(4,3),
    cost_score       numeric(4,3),
    failure_rate     numeric(4,3),
    retry_count      integer NOT NULL DEFAULT 0,
    health_status    text NOT NULL DEFAULT 'unknown' CHECK (health_status IN ('unknown','healthy','degraded','unhealthy')),
    heartbeat_at     timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    emergency_stopped     boolean NOT NULL DEFAULT false,
    emergency_reason      text,
    emergency_stopped_at  timestamptz
);
CREATE INDEX IF NOT EXISTS idx_agents_manager_id ON ai_core.agents(manager_id);
CREATE INDEX IF NOT EXISTS idx_agents_status     ON ai_core.agents(status);

CREATE TABLE IF NOT EXISTS ai_core.capabilities (
