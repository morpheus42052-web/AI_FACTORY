    version     text NOT NULL,
    model       text,
    prompt      text,
    config      jsonb,
    is_active   boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_agent_versions_agent_id ON ai_core.agent_versions(agent_id);

CREATE TABLE IF NOT EXISTS ai_core.agent_health (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id       bigint NOT NULL REFERENCES ai_core.agents(id),
    health_status  text CHECK (health_status IS NULL OR health_status IN ('unknown','healthy','degraded','unhealthy')),
