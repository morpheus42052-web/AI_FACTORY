CREATE TABLE IF NOT EXISTS ai_core.tasks (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_code              text UNIQUE,
    objective              text,
    status                 text NOT NULL DEFAULT 'created' CHECK (status IN ('created','planned','queued','assigned','running','qc','completed','failed','retrying','blocked','paused','cancelled','escalated')),
    priority               integer NOT NULL DEFAULT 5,
    required_capabilities  text[],
    parent_task_id         bigint REFERENCES ai_core.tasks(id),
    created_by             text,
    payload                jsonb,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    started_at             timestamptz,
    completed_at           timestamptz
);
CREATE INDEX IF NOT EXISTS idx_tasks_parent_task_id ON ai_core.tasks(parent_task_id);
CREATE INDEX IF NOT EXISTS idx_tasks_status         ON ai_core.tasks(status);

